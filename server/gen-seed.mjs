// Generates server/seed.sql from the app's static dataset
// (mobile/src/data/dataset.ts). Produces the reference ontology + a demo user
// "Alan" with three check-ups (so biomarker history/trends come from real rows).
//
//   node server/gen-seed.mjs   →   server/seed.sql
//   psql "$DATABASE_URL" -f server/seed.sql

import fs from 'node:fs';
import path from 'node:path';

const DATASET = path.resolve('mobile/src/data/dataset.ts');
const OUT = path.resolve('server/seed.sql');
const src = fs.readFileSync(DATASET, 'utf8');

// dataset.ts values are JSON.stringify output (quoted keys) → valid JSON. Extract
// each with a balanced-delimiter scan (regex can't handle nesting / `as const`).
function grab(name) {
  let i = src.indexOf('export const ' + name);
  if (i < 0) throw new Error('not found: ' + name);
  i = src.indexOf('=', i) + 1;
  while (/\s/.test(src[i])) i++;
  const open = src[i], close = open === '[' ? ']' : '}';
  const start = i;
  let depth = 0, inStr = false, esc = false;
  for (; i < src.length; i++) {
    const ch = src[i];
    if (inStr) {
      if (esc) esc = false;
      else if (ch === '\\') esc = true;
      else if (ch === '"') inStr = false;
      continue;
    }
    if (ch === '"') inStr = true;
    else if (ch === open) depth++;
    else if (ch === close && --depth === 0) return JSON.parse(src.slice(start, i + 1));
  }
  throw new Error('unbalanced: ' + name);
}

const META = grab('META');
const SYSTEMS = grab('SYSTEMS_META');
const BIOMARKERS = grab('BIOMARKERS');
const PLAN = grab('PLAN');
const RECORDS = grab('RECORDS');

// ── SQL helpers ──────────────────────────────────────────────────────────────
const q = (v) => (v == null ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const j = (v) => `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`;
const n = (v) => (v == null ? 'null' : Number(v));

const USER_ID = '00000000-0000-0000-0000-000000000001';
// three check-ups map to the three history points every marker carries
const CHECKUPS = [
  { id: '00000000-0000-0000-0000-0000000000c1', date: '2025-02-01', score: 78, bio: 33.0, idx: 0 },
  { id: '00000000-0000-0000-0000-0000000000c2', date: '2025-05-01', score: 80, bio: 32.2, idx: 1 },
  { id: '00000000-0000-0000-0000-0000000000c3', date: META.updatedAt, score: META.score, bio: META.bioAge, idx: 2 },
];

const out = [];
out.push('-- AUTO-GENERATED by server/gen-seed.mjs — do not edit by hand.');
out.push('begin;');

// systems
SYSTEMS.forEach((s, i) => {
  out.push(`insert into body_systems (key, name, sort) values (${q(s.key)}, ${j(s.name)}, ${i}) on conflict (key) do update set name = excluded.name, sort = excluded.sort;`);
});

// catalog
for (const b of BIOMARKERS) {
  out.push(`insert into biomarker_catalog (id, system_key, abbr, name, unit, ref_low, ref_high, optimal_low, optimal_high, what, why, related, actions) values (${q(b.id)}, ${q(b.system)}, ${q(b.abbr)}, ${j(b.name)}, ${q(b.unit)}, ${n(b.refLow)}, ${n(b.refHigh)}, ${n(b.optimalLow)}, ${n(b.optimalHigh)}, ${j(b.what)}, ${j(b.why)}, ${j(b.related)}, ${j(b.actions)}) on conflict (id) do nothing;`);
}

// demo user + profile
out.push(`insert into users (id, phone, name) values (${q(USER_ID)}, '+7 701 234 56 78', 'Alan') on conflict (id) do nothing;`);
out.push(`insert into profiles (user_id, sex, age_range, city, goals, sleep, activity, real_age) values (${q(USER_ID)}, 'm', '30–39', 'almaty', ${j(['energy', 'longevity'])}, '6–7', 'mid', ${META.realAge}) on conflict (user_id) do update set updated_at = now();`);

// check-ups + results + system scores
for (const c of CHECKUPS) {
  const latest = c.idx === 2;
  out.push(`insert into checkups (id, user_id, drawn_at, lab, city, status, score, bio_age, real_age) values (${q(c.id)}, ${q(USER_ID)}, ${q(c.date)}, 'INVIVO', 'Алматы', 'ready', ${c.score}, ${c.bio}, ${META.realAge}) on conflict (id) do nothing;`);
  for (const b of BIOMARKERS) {
    const hv = b.history[c.idx]?.value ?? b.value;
    out.push(`insert into biomarker_results (checkup_id, marker_id, value, status) values (${q(c.id)}, ${q(b.id)}, ${n(hv)}, ${q(b.status)}) on conflict (checkup_id, marker_id) do nothing;`);
  }
  if (latest) {
    for (const s of SYSTEMS) {
      out.push(`insert into system_scores (checkup_id, system_key, score, summary) values (${q(c.id)}, ${q(s.key)}, ${s.score}, ${j(s.summary)}) on conflict (checkup_id, system_key) do nothing;`);
    }
  }
}

// documents
for (const r of RECORDS) {
  out.push(`insert into documents (user_id, title, doc_date, source, lab, marker_count) values (${q(USER_ID)}, ${q(r.title)}, ${q(r.date)}, ${q(r.source)}, ${q(r.lab)}, ${r.markerCount});`);
}

// plan
for (const p of PLAN) {
  const pid = `00000000-0000-0000-0000-0000000000${(p.rank + 10).toString(16)}0`;
  out.push(`insert into plan_priorities (id, user_id, rank, marker_id, title, goal, why, retest_weeks) values (${q(pid)}, ${q(USER_ID)}, ${p.rank}, ${q(p.marker)}, ${j(p.title)}, ${j(p.goal)}, ${j(p.why)}, ${p.retestWeeks}) on conflict (id) do nothing;`);
  p.steps.forEach((st, i) => {
    out.push(`insert into plan_steps (priority_id, kind, title, detail, sort) values (${q(pid)}, ${q(st.kind)}, ${j(st.title)}, ${j(st.detail)}, ${i});`);
  });
}

out.push('commit;');

fs.writeFileSync(OUT, out.join('\n') + '\n');
console.log(`wrote ${OUT}`);
console.log(`  systems=${SYSTEMS.length} catalog=${BIOMARKERS.length} checkups=${CHECKUPS.length} results=${BIOMARKERS.length * CHECKUPS.length} docs=${RECORDS.length} priorities=${PLAN.length}`);
console.log(`  total statements: ${out.length - 3}`);
